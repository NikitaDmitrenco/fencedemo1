/**
 * Канал доставки заявки.
 *
 * Отдельный интерфейс, потому что канал у каждого клиента свой: у одного
 * Telegram, у другого почта, у третьего CRM. Подключение нового канала —
 * один файл, а не переделка формы и маршрута.
 */
export interface LeadChannel {
  /** Имя для логов и диагностики. */
  readonly name: string;
  /** Настроен ли канал: без обязательных переменных окружения он не берётся в работу. */
  isConfigured(): boolean;
  /** Отправляет готовый текст заявки. Бросает исключение при неудаче. */
  send(text: string): Promise<void>;
}
